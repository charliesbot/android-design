#!/usr/bin/env python3
"""Syncs the vendored Wear Compose sources in app/wear/compose/upstream/ to one androidx.wear.compose version.

Usage: sync_wear_compose.py <version>   (for example 1.8.0-alpha03)

For each artifact it downloads `<artifact>-<version>-sources.jar` from Google Maven, replaces the matching
directory under app/wear/compose/upstream/ with its contents (META-INF dropped), regenerates the English
`R.kt` from compose-material3's .aar, and records the version in app/wear/compose/upstream/VERSION.
Which files the build skips lives in app/wear/compose/build.gradle.kts, not here. Never edit upstream/ by hand.
"""
import io
import re
import shutil
import sys
import tempfile
import urllib.request
import xml.etree.ElementTree as ET
import zipfile
from pathlib import PurePosixPath
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEAR = ROOT / "app/wear/compose"
UPSTREAM = WEAR / "upstream"
GENERATED_R = WEAR / "src/generated/kotlin/androidx/wear/compose/material3/R.kt"
MAVEN = "https://dl.google.com/android/maven2/androidx/wear/compose"

# Artifact name -> directory under upstream/.
ARTIFACTS = {
    "compose-foundation": "foundation",
    "compose-material-core": "material-core",
    "compose-material3": "material3",
    "compose-navigation3": "navigation3",
}
RESOURCE_ARTIFACT = "compose-material3"


def artifact_url(artifact, version, suffix):
    return f"{MAVEN}/{artifact}/{version}/{artifact}-{version}{suffix}"


def download(url):
    with urllib.request.urlopen(url) as response:
        return response.read()


def extract_sources(jar_bytes, destination):
    """Replaces `destination` with the jar's files, skipping META-INF and directory entries."""
    destination = Path(destination)
    staging = Path(tempfile.mkdtemp(prefix="wear-sync-", dir=destination.parent))
    try:
        with zipfile.ZipFile(io.BytesIO(jar_bytes)) as jar:
            for name in sorted(jar.namelist()):
                parts = PurePosixPath(name).parts
                if name.endswith("/") or not parts or parts[0] == "META-INF":
                    continue
                if parts[0] == ".." or PurePosixPath(name).is_absolute():
                    raise ValueError(f"unsafe path in jar: {name}")
                target = staging.joinpath(*parts)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(jar.read(name))
        if destination.exists():
            shutil.rmtree(destination)
        staging.rename(destination)
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def unescape_android(text):
    """Resolves the backslash escapes aapt allows in resource strings."""
    return re.sub(r"\\(.)", lambda m: "\n" if m.group(1) == "n" else m.group(1), text or "")


def kotlin_string(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n")
    return f'"{escaped}"'


def generate_r_kt(values_xml, drawable_names, version):
    """Returns the Kotlin source of R (resource ids), WearStrings (English text) for one values.xml."""
    root = ET.fromstring(values_xml)
    strings = {}
    plurals = {}
    for element in root:
        name = element.get("name")
        if element.tag == "string":
            strings[name] = unescape_android("".join(element.itertext()))
        elif element.tag == "plurals":
            items = {item.get("quantity"): unescape_android("".join(item.itertext())) for item in element}
            plurals[name] = (items.get("one", items["other"]), items["other"])
    drawables = sorted(drawable_names)
    string_names = sorted(strings)
    plural_names = sorted(plurals)

    ids = {}
    for kind, names in (("drawable", drawables), ("plurals", plural_names), ("string", string_names)):
        for name in names:
            ids[(kind, name)] = len(ids) + 1

    out = [
        "package androidx.wear.compose.material3",
        "",
        f"// GENERATED by scripts/sync_wear_compose.py from compose-material3-{version}.aar. Do not edit.",
        "// Stands in for the aapt-generated R class and the Android resource lookup (English only).",
        "object R {",
    ]
    for kind, names in (("drawable", drawables), ("plurals", plural_names), ("string", string_names)):
        out.append(f"  object {kind} {{")
        for name in names:
            out.append(f"    const val {name} = {ids[(kind, name)]}")
        out.append("  }")
        out.append("")
    out[-1] = "}"
    out += ["", "object WearStrings {", "  val strings: Map<Int, String> =", "    mapOf("]
    for name in string_names:
        out.append(f"      R.string.{name} to {kotlin_string(strings[name])},")
    out += ["    )", "", "  val plurals: Map<Int, Pair<String, String>> =", "    mapOf("]
    for name in plural_names:
        one, other = plurals[name]
        out.append(f"      R.plurals.{name} to ({kotlin_string(one)} to {kotlin_string(other)}),")
    out += ["    )", "}", ""]
    return "\n".join(out)


def read_resources(aar_bytes):
    """Returns (values.xml text, sorted drawable names) from a compose-material3 .aar."""
    with zipfile.ZipFile(io.BytesIO(aar_bytes)) as aar:
        values = aar.read("res/values/values.xml").decode("utf-8")
        drawables = sorted(
            PurePosixPath(name).stem
            for name in aar.namelist()
            if name.startswith("res/drawable/") and not name.endswith("/")
        )
    return values, drawables


def sync(version, fetch=download, upstream=UPSTREAM, generated_r=GENERATED_R):
    upstream.mkdir(parents=True, exist_ok=True)
    for artifact, directory in ARTIFACTS.items():
        print(f"{artifact} {version}")
        extract_sources(fetch(artifact_url(artifact, version, "-sources.jar")), upstream / directory)
    values, drawables = read_resources(fetch(artifact_url(RESOURCE_ARTIFACT, version, ".aar")))
    generated_r.parent.mkdir(parents=True, exist_ok=True)
    generated_r.write_text(generate_r_kt(values, drawables, version))
    (upstream / "VERSION").write_text(version + "\n")


def main(argv):
    if len(argv) != 2 or argv[1].startswith("-"):
        print(__doc__)
        return 2
    sync(argv[1])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
