package bot.charlies.androiddesign.preview.domain.export

import bot.charlies.androiddesign.preview.domain.PreviewException
import bot.charlies.androiddesign.preview.model.Proposal

/** The package every exported file declares; the header tells the reader to change it. */
internal const val EXPORT_PACKAGE = "com.example.app"

/** The screens to export: [screen] alone, or every screen when it is null. */
internal fun screensToExport(proposal: Proposal, screen: String?): List<String> {
  if (screen == null) return proposal.screens.keys.toList()
  if (screen !in proposal.screens) {
    throw PreviewException(
      "unknown screen '$screen'; the proposal has ${proposal.screens.keys.joinToString()}",
    )
  }
  return listOf(screen)
}

/** The first line of an exported file's header comment. */
internal fun StringBuilder.appendGeneratedBy(title: String) {
  appendLine("// Generated by Android Design Preview from \"${title.replace("\n", " ")}\".")
}

/** The package note and the Material Symbols the file's `R.drawable` lookups need. */
internal fun StringBuilder.appendPackageAndDrawableNotes(file: FileContext) {
  appendLine("// Change the package to your app's namespace so R resolves.")
  if (file.drawables.isNotEmpty()) {
    appendLine("//")
    appendLine("// Add these Material Symbols (Rounded, weight 400, grade 0) as vector drawables.")
    appendLine("// A name ending in _filled is the same symbol with Fill 1:")
    file.drawables.forEach { appendLine("//   R.drawable.$it") }
  }
}
